#!/bin/bash
#
# tests/test-docs.sh - README.html is generated from README.md, so this checks
#                      the two have not drifted apart. No CouchDB, no network,
#                      and no pandoc: the check has to run everywhere or it
#                      quietly stops being run.
#
# The failure this exists to catch is a README.md edit committed without a
# re-render. Nothing breaks, which is the problem - the HTML just goes on
# confidently describing how the scripts used to work.
#
# usage: tests/test-docs.sh
#

_here="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd -- "${_here}/.." && pwd)"

MD="${REPO}/README.md"
HTML="${REPO}/README.html"
RENDER="${REPO}/tools/render-readme.sh"

PASS=0
FAIL=0
ok () { PASS=$((PASS + 1)); printf '  ok   %s\n' "$1"; }
no () { FAIL=$((FAIL + 1)); printf '  FAIL %s\n' "$1"; }

assert_eq () {
	if [ "$2" = "$3" ]; then ok "$1"; else
		no "$1"; printf '       expected: [%s]\n' "$2"; printf '       actual  : [%s]\n' "$3"
	fi
}

echo "== the generated README =="

assert_eq "README.md exists" "yes" "$([ -f "${MD}" ] && echo yes || echo no)"
assert_eq "the renderer exists and is executable" "yes" \
	"$([ -x "${RENDER}" ] && echo yes || echo no)"
assert_eq "README.html exists" "yes" "$([ -f "${HTML}" ] && echo yes || echo no)"

if [ ! -f "${HTML}" ] || [ ! -x "${RENDER}" ]; then
	echo
	printf '%s: %d passed, %d failed\n' "$(basename "$0")" "${PASS}" "${FAIL}"
	exit 1
fi

# The one that matters: was this HTML rendered from the README.md sitting here?
render_out="$("${RENDER}" --check 2>&1)"
render_rc=$?
assert_eq "README.html was rendered from the current README.md" "0" "${render_rc}"
if [ "${render_rc}" -ne 0 ]; then
	printf '       %s\n' "${render_out}"
	printf '       fix: tools/render-readme.sh, and commit both files together\n'
fi

assert_eq "it says it is generated, so nobody edits it by hand" "yes" \
	"$(grep -q 'GENERATED by tools/render-readme.sh' "${HTML}" && echo yes || echo no)"
assert_eq "and says so visibly on the page too" "yes" \
	"$(grep -q 'generated-note' "${HTML}" && echo yes || echo no)"

# Self-contained. This page gets opened from a file:// path on a machine that
# has lost its network - that is when you are reading it.
assert_eq "it fetches nothing at view time" "none" \
	"$(grep -oE '(src|href)="(https?:)?//[^\"]*"' "${HTML}" | sort -u | tr '\n' ' ' | sed 's/ $//' | grep . || echo none)"

# --- internal links -------------------------------------------------------
#
# Checked in the HTML rather than the Markdown on purpose: the ids pandoc emits
# are the ones a browser will actually resolve, so this catches a broken
# contents entry without this script having to reimplement GitHub's slug rules.

anchors="$(grep -oE 'href="#[^"]+"' "${HTML}" | sed 's/href="#//; s/"$//' | sort -u)"
ids="$(grep -oE ' id="[^"]+"' "${HTML}" | sed 's/ id="//; s/"$//' | sort -u)"

broken=""
while IFS= read -r a; do
	[ -z "${a}" ] && continue
	printf '%s\n' "${ids}" | grep -qxF "${a}" || broken+=" #${a}"
done <<< "${anchors}"

assert_eq "every internal link resolves to a heading on the page" "" "${broken}"
assert_eq "and there are links to check in the first place" "yes" \
	"$([ "$(printf '%s\n' "${anchors}" | grep -c .)" -gt 10 ] && echo yes || echo no)"

# --- the content actually survived the render ------------------------------
#
# A renderer misconfigured for the wrong Markdown flavour still produces a
# plausible-looking page; it just loses the tables and fences that carry most
# of what this README says.

assert_eq "tables came through as tables" "yes" \
	"$([ "$(grep -c '<table' "${HTML}")" -ge 3 ] && echo yes || echo no)"
assert_eq "fenced code blocks came through" "yes" \
	"$([ "$(grep -c '<pre' "${HTML}")" -ge 20 ] && echo yes || echo no)"
assert_eq "no raw markdown fences survived into the html" "0" \
	"$(grep -c '^```' "${HTML}")"

echo
printf '%s: %d passed, %d failed\n' "$(basename "$0")" "${PASS}" "${FAIL}"
[ "${FAIL}" -eq 0 ]
